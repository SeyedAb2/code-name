/* ============================================================================
   نمای سبک‌شدهٔ داده برای کلاینت

   مانیفست کامل ۷۸۷ کیلوبایت است و همهٔ ۱۳۸۹ فصل را دارد. صفحهٔ اصلی فقط
   نام و آمار ۷۰ مسیر را لازم دارد — اگر شیء کامل را به کامپوننت کلاینت
   بدهیم، Next تمامش را در payload سریال می‌کند و هر بازدیدکننده صدها
   کیلوبایت فصل‌هایی را می‌گیرد که قرار نیست ببیند.

   این توابع فقط همان چیزی را نگه می‌دارند که آن صفحه واقعاً می‌خواند.
   ========================================================================== */
import type { Chapter, Track } from "./types";

/** مسیر، بدون فهرست کامل فصل‌ها. */
export interface TrackSummary extends Omit<Track, "chapters"> {
  /** فقط فصل‌های آماده — برای محاسبهٔ پیشرفت و دکمهٔ «ادامه» همین کافی است. */
  chapters: Chapter[];
}

/**
 * فصل‌های نیامده حذف می‌شوند. در عمل از ۱۳۸۹ فصل فقط چند تا آماده‌اند،
 * پس payload از صدها کیلوبایت به چند کیلوبایت می‌رسد.
 *
 * نکته: `stats` از قبل حساب شده و دست‌نخورده می‌ماند، پس کارت همچنان
 * «۴۲ فصل» را درست نشان می‌دهد، حتی وقتی آرایه یکی دو عضو دارد.
 */
export function toSummary(track: Track): TrackSummary {
  return { ...track, chapters: track.chapters.filter((c) => c.ready) };
}

export const toSummaries = (tracks: Track[]): TrackSummary[] => tracks.map(toSummary);
